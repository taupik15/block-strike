#!/usr/bin/env node
"use strict";
// Keeps offline-assets.js and sw.js in sync with the deployable JS files.
// Run from the repository root: node scripts/sync-offline-hashes.js
// Idempotent: writes nothing when the output would be unchanged.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = process.cwd();
const assetsPath = path.join(root, "offline-assets.js");
const workerPath = path.join(root, "sw.js");
const read = (p) => fs.readFileSync(p, "utf8");
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const fileSha = (rel) => sha256(fs.readFileSync(path.join(root, rel)));

let assets = read(assetsPath);
let worker = read(workerPath);

// 1) Critical files: keep the same list, refresh each hash from the file on disk.
const critMatch = assets.match(/const OFFLINE_CRITICAL_HASHES=\{[^}]*\};/);
if (!critMatch) throw new Error("OFFLINE_CRITICAL_HASHES not found in offline-assets.js");
const keys = [...critMatch[0].matchAll(/"(js\/[^"]+)":"[0-9a-f]{64}"/g)].map((m) => m[1]);
if (!keys.length) throw new Error("No critical entries parsed");
const hashes = {};
for (const key of keys) hashes[key] = fileSha(key);
assets = assets.replace(critMatch[0], "const OFFLINE_CRITICAL_HASHES=" + JSON.stringify(hashes) + ";");
assets = assets.replace(/const OFFLINE_NAV_SHA256="[0-9a-f]{64}";/, 'const OFFLINE_NAV_SHA256="' + hashes["js/bsp-local-nav.js"] + '";');

// 2) Build id: fingerprint of every shipped JS file (excludes the generated files).
//    Any code change gives a new id, so sw.js changes and browsers pick up the update.
const jsFiles = [];
(function walk(dir) {
  for (const name of fs.readdirSync(path.join(root, dir))) {
    const rel = path.posix.join(dir, name);
    if (fs.statSync(path.join(root, rel)).isDirectory()) walk(rel);
    else if (name.endsWith(".js")) jsFiles.push(rel);
  }
})("js");
jsFiles.sort();
const fingerprint = sha256(jsFiles.map((f) => f + ":" + fileSha(f)).join("\n")).slice(0, 12);
const build = "AR11.10.22I-" + fingerprint;
assets = assets.replace(/const OFFLINE_BUILD="[^"]*";/, 'const OFFLINE_BUILD="' + build + '";');

// 3) sw.js first-line marker carries the same build id.
worker = worker.replace(/^\/\* AR11[^\n]*/m, "/* " + build + ": generated by scripts/sync-offline-hashes.js */");

if (read(assetsPath) === assets && read(workerPath) === worker) {
  console.log("Offline hashes already in sync (" + build + ").");
  process.exit(0);
}
fs.writeFileSync(assetsPath, assets, "utf8");
fs.writeFileSync(workerPath, worker, "utf8");
console.log("Offline hashes updated: " + build + " (" + keys.length + " critical, " + jsFiles.length + " js files).");
